import { describe, expect, it } from 'vitest';
import { type CanvasNode, type Edge, type Project, type Theme, tokenHandle } from './model';
import { createColorNode, createPaletteNode, createTokenNode, makeEdge } from './defaults';
import { EXPORT_FORMATS, type ExportOptions, exportProject } from './export';

const LIGHT: Theme = { id: 'light', name: 'Light', dark: false };
const DARK: Theme = { id: 'dark', name: 'Dark', dark: true };
const at = { x: 0, y: 0 };

function project(nodes: CanvasNode[], edges: Edge[], themes: Theme[] = [LIGHT, DARK]): Project {
  return { schema: 2, id: 'p', name: 'Export test', createdAt: 0, updatedAt: 0, themes, nodes, edges, preview: { bindings: {} } };
}

const toLight = (source: string, target: string, sourceHandle = 'out') => makeEdge(source, sourceHandle, target, tokenHandle('light'));
const toDark = (source: string, target: string, sourceHandle = 'out') => makeEdge(source, sourceHandle, target, tokenHandle('dark'));

function sample(themes?: Theme[]): Project {
  const nodes: CanvasNode[] = [
    createColorNode({ id: 'brand', name: 'Brand', position: at, space: 'rgb', hex: '#3B82F6' }),
    createPaletteNode({ id: 'neutral', name: 'Neutral', position: at, steps: 3, naming: 'hundreds', chroma: 0, chromaMode: 'constant', lightStart: 95, lightEnd: 20 }),
    createTokenNode({ id: 'surface', name: 'bg/surface', position: at, description: 'Page background' }),
    createTokenNode({ id: 'text', name: 'text/primary', position: at }),
    createTokenNode({ id: 'btn', name: 'button/bg', position: at }),
    createTokenNode({ id: 'hover', name: 'button/hover', position: at }),
    createTokenNode({ id: 'unused', name: 'unused/token', position: at }),
  ];
  const edges = [
    toLight('neutral', 'surface', 's0'), toDark('neutral', 'surface', 's2'),
    toLight('neutral', 'text', 's2'), toDark('neutral', 'text', 's0'),
    toLight('brand', 'btn'), toLight('btn', 'hover'),
  ];
  return project(nodes, edges, themes);
}

const opts = (over: Partial<ExportOptions> = {}): ExportOptions => ({
  format: 'css', colorFormat: 'hex', includePrimitives: true, useAliases: true, ...over,
});

const block = (css: string, selector: string) => {
  const start = css.indexOf(selector);
  return start < 0 ? '' : css.slice(start, css.indexOf('}', start) + 1);
};

describe('EXPORT_FORMATS', () => {
  it('describes all four formats', () => {
    expect(Object.keys(EXPORT_FORMATS)).toEqual(['css', 'tailwind', 'dtcg', 'json']);
    for (const f of Object.values(EXPORT_FORMATS)) expect(f.fileName).toMatch(/\.\w+$/);
  });
});

describe('CSS export', () => {
  const css = exportProject(sample(), opts());
  const root = block(css, ':root {');
  const dark = block(css, '[data-theme="dark"] {');

  it('writes primitives and aliased tokens for the primary theme', () => {
    expect(css).toContain('/* Generated by 0colors — Export test */');
    expect(root).toContain('  --brand: #3B82F6;');
    expect(root).toMatch(/--neutral-100: #[0-9A-F]{6};/);
    expect(root).toContain('--neutral-300:');
    expect(root).toContain('  --bg-surface: var(--neutral-100);');
    expect(root).toContain('  --text-primary: var(--neutral-300);');
    expect(root).toContain('  --button-bg: var(--brand);');
    expect(root).toContain('  --button-hover: var(--button-bg);');
    expect(root).toContain('/* unused/token: not assigned */');
  });

  it('only writes what changes in other themes', () => {
    expect(dark).toContain('--bg-surface: var(--neutral-300);');
    expect(dark).toContain('--text-primary: var(--neutral-100);');
    expect(dark).not.toContain('--brand:');
    expect(dark).not.toContain('--button-bg');
    expect(dark).not.toContain('not assigned');
  });

  it('notes when a theme has no differences', () => {
    const p = sample();
    const same = { ...p, edges: p.edges.filter((e) => !e.targetHandle.endsWith('dark')) };
    expect(block(exportProject(same, opts()), '[data-theme="dark"] {')).toContain('/* Same as Light */');
  });

  it('inlines values when primitives are excluded but keeps token aliases', () => {
    const out = exportProject(sample(), opts({ includePrimitives: false }));
    expect(out).not.toContain('--brand:');
    expect(out).toMatch(/--bg-surface: #[0-9A-F]{6};/);
    expect(out).toContain('--button-bg: #3B82F6;');
    expect(out).toContain('--button-hover: var(--button-bg);');
  });

  it('writes literal values without aliases', () => {
    const out = exportProject(sample(), opts({ useAliases: false }));
    expect(out).toContain('--button-hover: #3B82F6;');
    expect(out).not.toContain('var(--');
  });

  it('uses the chosen color notation', () => {
    expect(exportProject(sample(), opts({ colorFormat: 'oklch' }))).toMatch(/--brand: oklch\([\d.]+% [\d.]+ [\d.]+\);/);
    expect(exportProject(sample(), opts({ colorFormat: 'rgb' }))).toContain('--brand: rgb(59 130 246);');
    expect(exportProject(sample(), opts({ colorFormat: 'hsl' }))).toMatch(/--brand: hsl\(/);
  });

  it('keeps token names when a primitive would collide', () => {
    const p = project(
      [createColorNode({ id: 'b', name: 'Brand', position: at, space: 'rgb', hex: '#3B82F6' }), createTokenNode({ id: 't', name: 'brand', position: at })],
      [toLight('b', 't')],
    );
    const out = exportProject(p, opts());
    expect(out).toContain('--brand-2: #3B82F6;');
    expect(out).toContain('--brand: var(--brand-2);');
  });
});

describe('Tailwind export', () => {
  it('writes an @theme block with dark overrides', () => {
    const out = exportProject(sample(), opts({ format: 'tailwind' }));
    expect(out).toContain('@import "tailwindcss";');
    expect(out).toContain('@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));');
    expect(out).toContain('@theme {');
    expect(out).toContain('--color-brand: #3B82F6;');
    expect(out).toContain('--color-bg-surface: var(--color-neutral-100);');
    expect(block(out, '[data-theme="dark"] {')).toContain('--color-bg-surface: var(--color-neutral-300);');
  });

  it('names the dark variant after the first dark theme', () => {
    const out = exportProject(sample([LIGHT, { id: 'dark', name: 'Night', dark: true }]), opts({ format: 'tailwind' }));
    expect(out).toContain('@custom-variant dark (&:where([data-theme=night], [data-theme=night] *));');
    expect(out).toContain('[data-theme="night"] {');
  });

  it('omits the dark variant when there is no dark theme', () => {
    expect(exportProject(sample([LIGHT]), opts({ format: 'tailwind' }))).not.toContain('@custom-variant');
  });
});

describe('DTCG export', () => {
  const parse = (over: Partial<ExportOptions> = {}) => JSON.parse(exportProject(sample(), opts({ format: 'dtcg', ...over })));

  it('nests primitives and tokens with DTCG color values', () => {
    const doc = parse();
    expect(doc.$description).toContain('Light');
    expect(doc.primitive.brand.$type).toBe('color');
    expect(doc.primitive.brand.$value).toEqual({
      colorSpace: 'srgb',
      components: [Math.round((59 / 255) * 1e4) / 1e4, Math.round((130 / 255) * 1e4) / 1e4, Math.round((246 / 255) * 1e4) / 1e4],
      alpha: 1,
      hex: '#3b82f6',
    });
    expect(doc.primitive.neutral['100'].$type).toBe('color');
  });

  it('writes aliases as curly-brace references and keeps descriptions', () => {
    const doc = parse();
    expect(doc.bg.surface.$value).toBe('{primitive.neutral.100}');
    expect(doc.bg.surface.$description).toBe('Page background');
    expect(doc.button.bg.$value).toBe('{primitive.brand}');
    expect(doc.button.hover.$value).toBe('{button.bg}');
    expect(doc.unused).toBeUndefined();
  });

  it('exports the requested theme', () => {
    expect(parse({ themeId: 'dark' }).bg.surface.$value).toBe('{primitive.neutral.300}');
  });

  it('inlines values without primitives and supports oklch', () => {
    const doc = parse({ includePrimitives: false });
    expect(doc.primitive).toBeUndefined();
    expect(doc.bg.surface.$value.colorSpace).toBe('srgb');
    const ok = parse({ colorFormat: 'oklch' });
    expect(ok.primitive.brand.$value.colorSpace).toBe('oklch');
    expect(ok.primitive.brand.$value.components[0]).toBeGreaterThan(0);
    expect(ok.primitive.brand.$value.components[0]).toBeLessThan(1);
  });

  it('uses $root when a token is also a group', () => {
    const p = project(
      [
        createColorNode({ id: 'b', name: 'Brand', position: at, space: 'rgb', hex: '#3B82F6' }),
        createTokenNode({ id: 'a', name: 'accent', position: at }),
        createTokenNode({ id: 'ah', name: 'accent/hover', position: at }),
      ],
      [toLight('b', 'a'), toLight('a', 'ah')],
    );
    const doc = JSON.parse(exportProject(p, opts({ format: 'dtcg' })));
    expect(doc.accent.$root.$type).toBe('color');
    expect(doc.accent.$root.$value).toBe('{primitive.brand}');
    expect(doc.accent.hover.$value).toBe('{accent.$root}');
  });
});

describe('JSON export', () => {
  it('resolves every theme to plain values in canvas order', () => {
    const doc = JSON.parse(exportProject(sample(), opts({ format: 'json', includePrimitives: false })));
    expect(Object.keys(doc)).toEqual(['Light', 'Dark']);
    expect(Object.keys(doc.Light.tokens)).toEqual(['bg/surface', 'text/primary', 'button/bg', 'button/hover', 'unused/token']);
    expect(doc.Light.tokens['bg/surface']).toMatch(/^#[0-9A-F]{6}$/);
    expect(doc.Light.tokens['unused/token']).toBeNull();
    expect(doc.Light.tokens['button/hover']).toBe('#3B82F6');
    expect(doc.Dark.tokens['button/bg']).toBe('#3B82F6');
    expect(doc.Dark.tokens['bg/surface']).toBe(doc.Light.tokens['text/primary']);
    expect(doc.Light.primitives).toBeUndefined();
  });

  it('includes primitives on request', () => {
    const doc = JSON.parse(exportProject(sample(), opts({ format: 'json' })));
    expect(doc.Light.primitives.brand).toBe('#3B82F6');
    expect(Object.keys(doc.Light.primitives)).toEqual(['brand', 'neutral-100', 'neutral-200', 'neutral-300']);
  });
});
